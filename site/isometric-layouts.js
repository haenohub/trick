export function floorTileCode(nav, col, row) {
  const mask = nav.transitions[row]?.[col] ?? 0,
    hash = Math.abs(col * 31 + row * 17);
  if (mask === 0) return 24 + (hash % 8);
  if (mask !== 15) return mask;
  const plaza = (nav.rooms || []).findIndex(
    ([x, y]) => Math.hypot(x - col, y - row) < 0.75,
  );
  return 16 + (plaza >= 0 ? (plaza % 2 ? 6 : 1) : [0, 2, 4, 7][hash % 4]);
}
